const norm = (s: string) => s.replace(/[-־'"׳״]/g, " ").replace(/\s+/g, " ").trim();
const INDEX = new Map<string, string>();
for (const [r, list] of Object.entries(MAP)) for (const c of list) if (!INDEX.has(norm(c))) INDEX.set(norm(c), r);

/* the region a city belongs to, or "" when the city is not in the list */
export function regionOf(city: string | null | undefined) {
  return city ? INDEX.get(norm(city)) || "" : "";
}

export function placeLabel(city?: string | null, region?: string | null) {
  return [city, region && region !== city ? region : ""].filter(Boolean).join(" · ");
}
