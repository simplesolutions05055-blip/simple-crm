/* settings may hold an edited copy of a template, by kind */
export function clientForms(over?: Record<string, IntakeForm> | null): IntakeForm[] {
  return CLIENT_FORMS.map((f) => {
    const o = over?.[f.kind];
    return o && Array.isArray(o.sections) && o.sections.length ? { ...f, ...o, kind: f.kind } : f;
  });
}
export const clientFormByKind = (k: string, over?: Record<string, IntakeForm> | null) => clientForms(over).find((f) => f.kind === k);

export function newToken() {
  const b = new Uint8Array(16);
  crypto.getRandomValues(b);
  return Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
}

/* where the link stands, for the documents list */
export function intakeStatus(d: { token?: string | null; submitted_at?: string | null; opened_at?: string | null; reopened_at?: string | null; data?: { filled?: number } | null }) {
  if (!d.token) return null;
  if (d.submitted_at) return { label: "מולא", cls: "ok" };
  if (d.reopened_at) return { label: "פתוח למילוי", cls: "warn" };
  if (d.data?.filled) return { label: "בתהליך", cls: "warn" };
  if (d.opened_at) return { label: "נפתח", cls: "info" };
  return { label: "נשלח", cls: "" };
}

