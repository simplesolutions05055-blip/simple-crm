export const formByKind = (k: string) => INTAKE_FORMS.find((f) => f.kind === k);

/* plain text for sending to the office chat */
export function formText(f: IntakeForm, a: Answers, who: string) {
  const out = ["# " + f.title + (who ? " · " + who : ""), ""];
  for (const s of f.sections) {
    out.push("## " + s.title);
    for (const x of s.fields) {
      const v = a[x.id];
      const val = Array.isArray(v) ? v.join(" · ") : (v || "").trim();
      out.push("- " + x.q + ": " + (val || "לא מולא"));
    }
    out.push("");
  }
  return out.join("\n");
}

export function filledCount(f: IntakeForm, a: Answers) {
  let n = 0, all = 0;
  for (const s of f.sections) for (const x of s.fields) { all++; const v = a[x.id]; if (Array.isArray(v) ? v.length : (v || "").trim()) n++; }
  return { n, all };
}
